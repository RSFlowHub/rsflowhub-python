"""Regenerate the SDK's typed layer from the live OpenAPI document.

    python scripts/generate.py                                      # https://rsflowhub.com/api/v1/openapi.json
    python scripts/generate.py http://localhost/api/v1/openapi.json
    python scripts/generate.py path/to/openapi.json

Writes (never edit these by hand):
    src/rsflowhub/_generated/operations.py   resource -> method -> (HTTP method, path)
    src/rsflowhub/_generated/resources.py    resource classes + client properties
    src/rsflowhub/_generated/resources.pyi   typed method stubs (autocomplete, mypy)
    docs/ENDPOINTS.md                        reference table of every method

The SDK works without running this (see _operations.py); it only adds types
and docs. The "Sync with API" GitHub workflow runs it weekly. Standard library only.
"""

from __future__ import annotations

import json
import keyword
import os
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "src" / "rsflowhub" / "_generated"
SOURCE = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("RSFLOWHUB_SPEC_URL", "https://rsflowhub.com/api/v1/openapi.json")
HEADER = "# Generated by scripts/generate.py from the RSFlowHub OpenAPI document. Do not edit.\n"


def load(source: str) -> dict:
    if re.match(r"^https?://", source):
        req = urllib.request.Request(source, headers={"Accept": "application/json", "User-Agent": "rsflowhub-python-generator"})
        with urllib.request.urlopen(req, timeout=30) as resp:  # noqa: S310 (fixed, user-supplied URL)
            return json.loads(resp.read().decode())
    return json.loads(Path(source).read_text(encoding="utf-8"))


def snake(name: str) -> str:
    # Same two passes as rsflowhub._operations.snake (askAQuestion -> ask_a_question).
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()


def pascal(name: str) -> str:
    return name[:1].upper() + name[1:]


def py_type(schema: dict) -> str:
    if schema.get("format") == "binary":
        t = "FileInput"
    elif schema.get("enum"):
        t = "Literal[" + ", ".join(json.dumps(v) for v in schema["enum"]) + "]"
    else:
        t = {
            "string": "str",
            "integer": "int",
            "number": "float",
            "boolean": "bool",
        }.get(schema.get("type", ""), "")
        if not t:
            if schema.get("type") == "array":
                t = f"List[{py_type(schema.get('items') or {})}]"
            elif schema.get("type") == "object":
                t = "Dict[str, Any]"
            else:
                t = "Any"
    return f"Optional[{t}]" if schema.get("nullable") and t != "Any" else t


def doc_for(schema: dict) -> str:
    parts = []
    if schema.get("description"):
        parts.append(schema["description"])
    for key, label in (("maxLength", "Max {} characters."), ("maxItems", "Max {} items."), ("minItems", "Min {} items.")):
        if key in schema:
            parts.append(label.format(schema[key]))
    if "minimum" in schema or "maximum" in schema:
        parts.append(f"Range {schema.get('minimum', '…')} to {schema.get('maximum', '…')}.")
    return " ".join(parts)


def body_schema(op: dict) -> dict | None:
    content = (op.get("requestBody") or {}).get("content") or {}
    for value in content.values():
        return value.get("schema")
    query = [p for p in op.get("parameters", []) if p.get("in") == "query"]
    if not query:
        return None
    return {
        "type": "object",
        "properties": {p["name"]: p.get("schema") or {} for p in query},
        "required": [p["name"] for p in query if p.get("required")],
    }


def main() -> None:
    try:
        spec = load(SOURCE)
    except Exception as e:  # noqa: BLE001
        sys.exit(f"Could not read the OpenAPI document from {SOURCE}: {e}")
    if not isinstance(spec, dict) or "openapi" not in spec or "paths" not in spec:
        sys.exit(f"{SOURCE} is not an OpenAPI document.")

    ops: dict[str, dict[str, dict]] = {}
    for path, operations in spec["paths"].items():
        for http, op in operations.items():
            sdk = op.get("x-rsflowhub-sdk") if isinstance(op, dict) else None
            if isinstance(sdk, dict) and sdk.get("resource") and sdk.get("method"):
                ops.setdefault(sdk["resource"], {})[sdk["method"]] = {"http": http.upper(), "path": path, "op": op}
    if not ops:
        sys.exit("No operations with x-rsflowhub-sdk found.")
    resources = sorted(ops)
    titles = {r: (ops[r][sorted(ops[r])[0]]["op"].get("tags") or [pascal(r)])[0] for r in resources}
    PKG.mkdir(parents=True, exist_ok=True)
    (PKG / "__init__.py").write_text(HEADER, encoding="utf-8")

    # 1. Operation map --------------------------------------------------------
    lines = [HEADER, "from typing import Dict, Tuple", "", "OPERATIONS: Dict[str, Dict[str, Tuple[str, str]]] = {"]
    for r in resources:
        lines.append(f"    {r!r}: {{")
        for m in sorted(ops[r]):
            lines.append(f"        {m!r}: ({ops[r][m]['http']!r}, {ops[r][m]['path']!r}),")
        lines.append("    },")
    lines.append("}")
    (PKG / "operations.py").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # 2. Runtime resource classes + client mixins --------------------------------
    rt = [HEADER, "from typing import Dict, Tuple, Type, cast", "", "from .._resource import AsyncResource, Resource", ""]
    for r in resources:
        rt += ["", f"class {pascal(r)}Resource(Resource):", f'    """{titles[r]}: ``client.{snake(r)}``."""', ""]
        rt += ["", f"class Async{pascal(r)}Resource(AsyncResource):", f'    """{titles[r]}: ``client.{snake(r)}`` (async)."""', ""]
    rt += ["", "CLASSES: Dict[str, Tuple[Type[Resource], Type[AsyncResource]]] = {"]
    rt += [f"    {r!r}: ({pascal(r)}Resource, Async{pascal(r)}Resource)," for r in resources]
    rt += ["}", ""]
    for prefix, base in (("", "Resource"), ("Async", "AsyncResource")):
        rt += ["", f"class {prefix}ResourcesMixin:", f'    """Typed resource properties of the {"async " if prefix else ""}client."""', ""]
        rt += [f"    def resource(self, name: str) -> {base}:  # implemented by the client", "        raise NotImplementedError", ""]
        for r in resources:
            rt += [
                "    @property",
                f"    def {snake(r)}(self) -> {prefix}{pascal(r)}Resource:",
                f'        """{titles[r]}."""',
                f'        return cast({prefix}{pascal(r)}Resource, self.resource({r!r}))',
                "",
            ]
    (PKG / "resources.py").write_text("\n".join(rt).rstrip() + "\n", encoding="utf-8")

    # 3. Typed stubs --------------------------------------------------------------
    st = [
        HEADER,
        "from pathlib import Path",
        "from typing import IO, Any, Dict, List, Literal, Mapping, Optional, Tuple, Type, Union, overload",
        "",
        "from .._resource import AsyncResource, Resource",
        "from .._response import Response",
        "",
        "Id = Union[int, str]",
        "FileInput = Union[bytes, Path, IO[bytes]]",
        "_OPTIONS = ''",
    ]
    options = "timeout: Optional[float] = ..., max_retries: Optional[int] = ..., extra_headers: Optional[Mapping[str, str]] = ..."
    st[-1] = ""

    def methods(r: str, is_async: bool) -> list[str]:
        out = []
        kw = "async def" if is_async else "def"
        for m in sorted(ops[r]):
            o = ops[r][m]
            op = o["op"]
            ids = [snake(p["name"]) + ": Id" for p in op.get("parameters", []) if p.get("in") == "path"]
            schema = body_schema(op)
            fields = []
            if schema:
                required = set(schema.get("required") or [])
                props = schema.get("properties") or {}
                for name in sorted(props, key=lambda n: (n not in required, list(props).index(n))):
                    if not name.isidentifier() or keyword.iskeyword(name) or name in ("timeout", "max_retries", "extra_headers"):
                        continue
                    t = py_type(props[name])
                    fields.append(f"{name}: {t}" + ("" if name in required else " = ..."))
            credits = (op.get("x-rsflowhub-credits") or {}).get("base_credits")
            doc_lines = [line for line in (op.get("summary"), op.get("description")) if line]
            doc_lines.append(f"``{o['http']} {o['path']}``" + (f", from {credits} credit{'s' if credits != 1 else ''}." if credits is not None else "."))
            if schema:
                for name, prop in (schema.get("properties") or {}).items():
                    d = doc_for(prop)
                    if d:
                        doc_lines.append(f":param {name}: {d}")
            doc = "\n        ".join(line.replace('"""', "'''") for line in doc_lines)
            pos = ", ".join(["self", *ids]) + (", /" if ids else "")
            name = snake(m)
            if keyword.iskeyword(name):
                continue
            out += [
                "    @overload",
                f"    {kw} {name}({pos}, *, {', '.join(fields + [options])}) -> Response:",
                f'        """{doc}"""',
                "    @overload",
                f"    {kw} {name}({', '.join(['self', *ids, 'body: Mapping[str, Any]'])}, /, *, {options}) -> Response: ...",
            ]
        return out

    for r in resources:
        st += ["", f"class {pascal(r)}Resource(Resource):", f'    """{titles[r]}: ``client.{snake(r)}``."""']
        st += methods(r, False)
        st += ["", f"class Async{pascal(r)}Resource(AsyncResource):", f'    """{titles[r]}: ``client.{snake(r)}`` (async)."""']
        st += methods(r, True)
    st += ["", "CLASSES: Dict[str, Tuple[Type[Resource], Type[AsyncResource]]]", ""]
    for prefix, base in (("", "Resource"), ("Async", "AsyncResource")):
        st += [f"class {prefix}ResourcesMixin:", f"    def resource(self, name: str) -> {base}: ..."]
        for r in resources:
            st += ["    @property", f"    def {snake(r)}(self) -> {prefix}{pascal(r)}Resource: ..."]
        st += [""]
    (PKG / "resources.pyi").write_text("\n".join(st).rstrip() + "\n", encoding="utf-8")

    # 4. Reference docs -------------------------------------------------------------
    md = [
        "# RSFlowHub Python SDK: method reference",
        "",
        "Generated by `scripts/generate.py` from the [RSFlowHub OpenAPI document](https://rsflowhub.com/api/v1/openapi.json). Do not edit.",
        "",
        "Every method exists on `RSFlowHub` and, awaitable, on `AsyncRSFlowHub`.",
        "",
    ]
    for r in resources:
        md += [f"## `client.{snake(r)}`: {titles[r]}", "", "| Method | HTTP | Description | Credits |", "| --- | --- | --- | --- |"]
        for m in sorted(ops[r]):
            o = ops[r][m]
            desc = str(o["op"].get("description") or o["op"].get("summary") or "").replace("|", "\\|")
            credits = (o["op"].get("x-rsflowhub-credits") or {}).get("base_credits")
            md.append(f"| `{snake(m)}()` | `{o['http']} {o['path']}` | {desc} | {'-' if credits is None else f'from {credits}'} |")
        md.append("")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "ENDPOINTS.md").write_text("\n".join(md), encoding="utf-8")

    count = sum(len(m) for m in ops.values())
    print(f"Generated {count} methods in {len(resources)} resources from {SOURCE}")


if __name__ == "__main__":
    main()
